#!/usr/bin/env python3
"""
Speech (text-to-speech) example for ModuLLe.

Requires Ollama >= 0.40.9 and a speech-capable model. lfm3-omni works on
CPU/GPU; phonon requires Apple's MLX runtime (Apple Silicon).

Run:
    OLLAMA_BASE_URL=http://192.168.2.150:11434 OLLAMA_SPEECH_MODEL=lfm3-omni \
        python3 examples/speech.py
"""

import os

from modulle import create_speech_processor
from modulle.config import OLLAMA_BASE_URL, OLLAMA_SPEECH_MODEL

SERVER = os.getenv("OLLAMA_BASE_URL", OLLAMA_BASE_URL)
MODEL = os.getenv("OLLAMA_SPEECH_MODEL", OLLAMA_SPEECH_MODEL)
OUTPUT = "speech.wav"

speech = create_speech_processor("ollama", model=MODEL, base_url=SERVER)

voices = speech.list_voices()
print(f"Model {MODEL} on {SERVER}")
print(f"Voices ({len(voices)}): {', '.join(voices[:8])}" + (" ..." if len(voices) > 8 else ""))

text = (
    "Hello! This audio was generated by ModuLLe using Ollama's speech API. "
    "Long text is split automatically and the audio is stitched back together."
)

path = speech.speak_to_file(text, OUTPUT, voice="default")
if path is None:
    raise SystemExit(
        f"Speech failed. Check that Ollama >= 0.40.9 is running and that "
        f"'{MODEL}' supports speech (ollama pull {MODEL})."
    )

print(f"\nWrote {path} ({os.path.getsize(path):,} bytes)")
